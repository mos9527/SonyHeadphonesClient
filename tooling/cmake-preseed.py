"""Preseed SDL feature checks, used by iOS CI builds

Like SDL's own cmake/PreseedMSVCCache.cmake, this does the same thing for other generators.
See also:
- https://github.com/libsdl-org/SDL/commit/3c00af1ac617d72037cb06618b8e0ca3e5d01520#diff-aaaad9c3cc7535b302ea14b72efd379ed87453b68cee72344a42151c13590c16 
- https://github.com/libsdl-org/SDL/issues/9949

This script is written by Claude Opus 5.5
"""

import argparse
import pathlib
import re
import sys

# Help strings CMake's check modules attach to their cached results.
CHECK_HELP_PREFIXES = (
    "Have include",
    "Have symbol ",
    "Have function ",
    "Have library ",
    "Test ",
    "CHECK_TYPE_SIZE",
)
ENTRY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):INTERNAL=(.*)$")


def cmake_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def collect(cache_text: str) -> list[tuple[str, str, str]]:
    entries = []
    help_lines: list[str] = []
    for line in cache_text.splitlines():
        if line.startswith("//"):
            help_lines.append(line[2:])
            continue
        help_text = " ".join(help_lines)
        help_lines = []
        match = ENTRY_RE.match(line)
        if not match:
            continue
        name, value = match.groups()
        if name.startswith("CMAKE_") or not help_text.startswith(CHECK_HELP_PREFIXES):
            continue
        entries.append((name, value, help_text))
    return entries


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("cache", type=pathlib.Path, help="CMakeCache.txt of the fast configure")
    parser.add_argument("output", type=pathlib.Path, help="preseed script to pass to `cmake -C`")
    args = parser.parse_args()

    entries = []
    if args.cache.is_file():
        entries = collect(args.cache.read_text(encoding="utf-8", errors="replace"))
    else:
        print(f"warning: {args.cache} not found, writing an empty preseed", file=sys.stderr)

    lines = [f"# Generated by {pathlib.Path(__file__).name} from {args.cache}"]
    lines += [
        f"set({name} {cmake_quote(value)} CACHE INTERNAL {cmake_quote(help_text)})"
        for name, value, help_text in entries
    ]
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Preseeded {len(entries)} check results into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

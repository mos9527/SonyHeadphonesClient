// Generate precomputed Material You theme table for MaterialYouTheme.hpp.
// Usage:
//   cd tooling/theme-generator
//   npm install
//   npm run generate
// Writes output to client/MaterialYouThemeTable.inc
import { argbFromHex, themeFromSourceColor } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const kDefaultSourceColor = "#364FA8"; // sca_primary (Sony fallback for neutral colors)

// ModelColor enum → source color mapping
// Values from Sony's cloud API (sca_source_color field)
const modelColorToSource = {
  0:  kDefaultSourceColor, // DEFAULT
  1:  kDefaultSourceColor, // BLACK
  2:  kDefaultSourceColor, // WHITE
  3:  kDefaultSourceColor, // SILVER
  4:  "#F7594E",           // RED
  5:  "#52688D",           // BLUE
  6:  "#D4B4B8",           // PINK
  7:  "#F7F799",           // YELLOW
  8:  "#B9DBCE",           // GREEN
  9:  kDefaultSourceColor, // GRAY
  10: kDefaultSourceColor, // GOLD
  11: "#ECE2C6",           // CREAM
  12: "#FCA48E",           // ORANGE
  13: "#504434",           // BROWN
  14: "#A9A0D1",           // VIOLET
};

const names = [
  "DEFAULT","BLACK","WHITE","SILVER","RED","BLUE","PINK","YELLOW",
  "GREEN","GRAY","GOLD","CREAM","ORANGE","BROWN","VIOLET"
];

const lines = [];
lines.push("// Auto-generated by tooling/theme-generator — do not edit manually");
lines.push("// Regenerate: cd tooling/theme-generator && npm install && npm run generate");
lines.push("// Source: material-color-utilities SchemeTonalSpot (dark mode)");
lines.push("");
lines.push("static constexpr Theme kThemeTable[] = {");

for (let i = 0; i < names.length; i++) {
  const source = modelColorToSource[i];
  const theme = themeFromSourceColor(argbFromHex(source));
  const d = theme.schemes.dark;
  const slots = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer"];
  const argbs = slots.map(s => "0x" + (d[s] >>> 0).toString(16).toUpperCase().padStart(8, '0'));
  lines.push(`    /* ${names[i].padEnd(7)} (${source}) */ {${argbs.join(", ")}},`);
}

lines.push("};");
lines.push("");

const thisDir = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(thisDir, "../../client/MaterialYouThemeTable.inc");
writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`Wrote ${outPath}`);
